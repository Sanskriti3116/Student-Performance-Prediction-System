from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from datetime import datetime


def generate_report_pdf(
    filename,
    student_name,
    email,
    department,
    semester,
    attendance,
    study_hours,
    performance_score,
    risk_level,
    rule_score,
    ml_score,
    final_score,
    performance_level
):

    pdf = SimpleDocTemplate(filename)

    styles = getSampleStyleSheet()

    content = []

    generated_date = datetime.now().strftime("%d-%m-%Y %H:%M")

    content.append(
        Paragraph(
            "STUDENT PERFORMANCE PREDICTION SYSTEM",
            styles["Title"]
        )
    )

    content.append(Spacer(1, 20))

    content.append(
        Paragraph(
            "==================================================",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "STUDENT INFORMATION",
            styles["Heading2"]
        )
    )

    content.append(
        Paragraph(
            f"Name : {student_name}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Email : {email}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Department : {department}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Semester : {semester}",
            styles["Normal"]
        )
    )

    content.append(Spacer(1, 15))

    content.append(
        Paragraph(
            "--------------------------------------------------",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "ACADEMIC SUMMARY",
            styles["Heading2"]
        )
    )

    content.append(
        Paragraph(
            f"Attendance : {attendance}%",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Study Hours : {study_hours}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Performance Score : {performance_score}/100",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Performance Level : {performance_level}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Risk Level : {risk_level}",
            styles["Normal"]
        )
    )

    content.append(Spacer(1, 15))

    content.append(
        Paragraph(
            "--------------------------------------------------",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "AI PREDICTION SUMMARY",
            styles["Heading2"]
        )
    )

    content.append(
        Paragraph(
            f"Rule-Based Score : {rule_score}/100",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"ML Prediction Score : {ml_score}/100",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Final AI Score : {final_score}/100",
            styles["Normal"]
        )
    )

    content.append(Spacer(1, 15))

    content.append(
        Paragraph(
            "--------------------------------------------------",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "RECOMMENDATIONS",
            styles["Heading2"]
        )
    )

    content.append(
        Paragraph(
            "✓ Improve attendance above 90%",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "✓ Maintain study hours above 6/day",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "✓ Sleep 7-8 hours daily",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "✓ Maintain positive mood",
            styles["Normal"]
        )
    )

    content.append(Spacer(1, 20))

    content.append(
        Paragraph(
            "==================================================",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "Generated By : Student Performance Prediction System",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            f"Date : {generated_date}",
            styles["Normal"]
        )
    )

    content.append(
        Paragraph(
            "==================================================",
            styles["Normal"]
        )
    )

    pdf.build(content)